func write(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestGitignoreSemantics(t *testing.T) {
	g := &gitIgnore{byDir: map[string][]ignorePattern{
		".":   parseGitignore([]byte("# comment\n*.log\n!keep.log\n/rootonly.txt\nbuild/\ndocs/**/*.tmp\n\\#hash\nfoo[0-9].txt\n")),
		"sub": parseGitignore([]byte("local.txt\n!*.log\n")),
	}}
	cases := []struct {
		rel   string
		dir   bool
		want  bool
		label string
	}{
		{"a.log", false, true, "glob anywhere"},
		{"x/y/a.log", false, true, "glob nested"},
		{"keep.log", false, false, "negation"},
		{"rootonly.txt", false, true, "anchored"},
		{"x/rootonly.txt", false, false, "anchored not nested"},
		{"build", true, true, "dir-only on dir"},
		{"build", false, false, "dir-only on file"},
		{"docs/a/b/c.tmp", false, true, "double star"},
		{"#hash", false, true, "escaped hash"},
		{"foo7.txt", false, true, "char class"},
		{"sub/local.txt", false, true, "nested gitignore"},
		{"local.txt", false, false, "nested gitignore scope"},
		{"sub/x.log", false, false, "nested negation overrides parent"},
	}
	for _, c := range cases {
		if got := g.Ignored(c.rel, c.dir); got != c.want {
			t.Errorf("%s: Ignored(%q)=%v want %v", c.label, c.rel, got, c.want)
		}
	}
}

func TestGeneratedHeader(t *testing.T) {
	for _, s := range []string{"// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x", "/**\n * @generated SignedSource<<abc>>\n */", "# Code generated by sqlc. DO NOT EDIT.\n", "// <auto-generated />\n"} {
		if !IsGeneratedSource([]byte(s)) {
			t.Errorf("not detected: %q", s)
		}
	}
	if IsGeneratedSource([]byte("package main\n// this code was generated with love? no.\n")) {
		t.Error("false positive")
	}
}

func TestDefaultExcludesAndGitignoreScan(t *testing.T) {
	root := t.TempDir()
	dup := `{"a": 1, "a": 2}`
	for _, rel := range []string{"src/ok.json", "node_modules/x/bad.json", "vendor/v.json", "dist/d.json", ".next/n.json",
		"coverage/c.json", "ignored/i.json", "src/skip.json", "src/keep.json", "app.min.js.map", "gen/types.generated.json"} {
		write(t, root, rel, dup)
	}
	write(t, root, "src/gen.json", `{"_": "@generated", "a": 1, "a": 2}`)
	write(t, root, "package-lock.json", `{"lockfileVersion": 1, "a": 1, "a": 2}`)
	write(t, root, "package.json", `{"name": "x"}`)
	write(t, root, ".gitignore", "ignored/\nsrc/*.json\n!src/keep.json\n!src/ok.json\n")
	write(t, root, ".git/info/exclude", "src/skip.json\n")
	write(t, root, "bin/b.json", dup) // bin/ is only a build dir next to .NET projects
	write(t, root, "cs/App.csproj", "<Project/>")
	write(t, root, "cs/bin/Debug/x.json", dup)

	rs, err := rules.LoadFiles("../../rules/packs/json/*.yaml")
	if err != nil {
		t.Fatal(err)
	}
	var dupRule []*rules.Rule
	for _, r := range rs {
		if r.ID == "JSON-QUAL-DUPLICATE-KEY" {
			dupRule = append(dupRule, r)
		}
	}
	files := func(o Options) []string {
		o.Root, o.Rules = root, dupRule
		rep, err := Scan(o)
		if err != nil {
			t.Fatal(err)
		}
		seen := map[string]bool{}
		for _, f := range rep.Findings {
			seen[f.Location.Path] = true
		}
		out := slices.Sorted(maps.Keys(seen))
		return out
	}
	got := files(Options{})
	want := []string{"bin/b.json", "src/keep.json", "src/ok.json"}
	if len(got) != len(want) {
		t.Fatalf("default scan files = %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("default scan files = %v, want %v", got, want)
		}
	}
	all := files(Options{NoDefaultExcludes: true, NoGitignore: true, IncludeGenerated: true})
	if len(all) < 14 {
		t.Fatalf("opt-out scan should see every file, got %v", all)
	}
	// lockfiles are excluded from review but still feed version detection
	u := versions.DetectUnit(root)
	if f, ok := u.Facts["npm.lockfile"]; !ok || f.Version != "1" {
		t.Fatalf("lockfile not used for detection: %+v", u.Facts)
	}
}
