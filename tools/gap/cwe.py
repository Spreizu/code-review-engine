"""CWE coverage checklist: the 2024 CWE Top 25 (view CWE-1435, read from cwe.mitre.org into the gitignored
cache) against crev's security rules, plus every distinct CWE crev rules carry. Memory-corruption entries
(out-of-bounds write/read, use-after-free, buffer overflows) are listed as not applicable: crev's languages
are memory-safe. Writes tools/gap/cwe-coverage.md."""
import collections
import html
import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(__file__))
from sonar import crev_rules, ROOT  # noqa: E402

CACHE = os.path.join(os.path.dirname(__file__), "cache")
VIEW = "https://cwe.mitre.org/data/definitions/1435.html"
MEMORY = {"787", "416", "125", "120", "121", "122"}


def top25():
    os.makedirs(CACHE, exist_ok=True)
    p = os.path.join(CACHE, "cwe-1435.html")
    if not os.path.exists(p):
        req = urllib.request.Request(VIEW, headers={"User-Agent": "curl/8 (crev gap checklist)"})
        with urllib.request.urlopen(req, timeout=60) as r:
            open(p, "wb").write(r.read())
    page = open(p, encoding="utf-8", errors="replace").read()
    seen = []
    for m in re.finditer(r"definitions/(\d+)\.html\"[^>]*>([^<]+)<", page):
        if m.group(1) not in [s[0] for s in seen] and m.group(1) != "1435":
            seen.append((m.group(1), html.unescape(m.group(2).strip())))
    return seen[:25]


def main():
    sec = [r for r in crev_rules() if r["status"] == "active" and r["cwe"]]
    by = collections.defaultdict(list)
    for r in sec:
        for c in r["cwe"]:
            by[c].append(r)
    lines = ["# CWE coverage", "", "Generated by `python tools/gap/cwe.py`. Rules = active crev rules tagged with the CWE (own tag or taxonomy).", "",
             "## CWE Top 25 (2024, view CWE-1435)", "", "| # | CWE | name | crev rules | languages |", "|---|---|---|---|---|"]
    cov = app = 0
    for i, (c, name) in enumerate(top25(), 1):
        rs = by.get(c, [])
        if c in MEMORY:
            lines.append(f"| {i} | CWE-{c} | {name} | n/a | memory-safe languages only |")
            continue
        app += 1
        cov += bool(rs)
        langs = sorted({r["lang"] for r in rs})
        lines.append(f"| {i} | CWE-{c} | {name} | {len(rs)} | {', '.join(langs) or '**none**'} |")
    lines[4:4] = [f"Applicable Top 25 entries covered: **{cov}/{app}** (6 memory-corruption entries not applicable).", ""]
    lines += ["", f"## All CWEs carried by crev rules ({len(by)})", "", "| CWE | rules | languages |", "|---|---|---|"]
    for c in sorted(by, key=lambda x: int(x)):
        lines.append(f"| CWE-{c} | {len(by[c])} | {', '.join(sorted({r['lang'] for r in by[c]}))} |")
    out = os.path.join(os.path.dirname(__file__), "cwe-coverage.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{out}: top25 {cov}/{app}, distinct CWEs {len(by)}")


if __name__ == "__main__":
    main()
