#!/usr/bin/env python3
"""Semgrep registry rules as a gap checklist (local use only).

semgrep/semgrep-rules is under the Semgrep Rules License v1.0: internal use is allowed, distribution
is not. The checkout lives in tools/gap/cache/semgrep-rules (gitignored, pinned commit below); crev
never embeds or ships their rules or test files. Only rule ids appear in crev (xref
semgrep:<rule-id>) and counts in tools/gap/semgrep-coverage.md.

  git clone --filter=blob:none https://github.com/semgrep/semgrep-rules tools/gap/cache/semgrep-rules
  git -C tools/gap/cache/semgrep-rules checkout 9bbf021d0acffa3095fcffd17b2bc7787eb4796d
  python tools/gap/semgrep.py

Coverage: a Semgrep rule counts as covered when a crev rule carries semgrep:<id>, or, for
security-category rules, a crev rule of the same language shares the CWE family ("cwe").
"""
import glob, os, re, sys
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sonar import crev_rules, FAMILY  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools/gap/cache/semgrep-rules")

def ensure_cache_module(cache):
    """Fetched sources include .go files; a nested go.mod keeps them out of `go build ./...`."""
    os.makedirs(cache, exist_ok=True)
    p = os.path.join(cache, "go.mod")
    if not os.path.exists(p):
        with open(p, "w", encoding="utf-8") as f:
            f.write("module crevcache\n")

ensure_cache_module(os.path.dirname(SRC))
LANGS = {"java": ["java"], "javascript": ["javascript"], "typescript": ["typescript", "javascript"], "python": ["python"],
         "go": ["go"], "kotlin": ["kotlin"], "php": ["php"], "dockerfile": ["dockerfile"], "terraform": ["hcl", "terraform"],
         "yaml": ["yaml"], "json": ["json"]}


def load():
    out = []
    for f in glob.glob(os.path.join(SRC, "**", "*.y*ml"), recursive=True):
        rel = os.path.relpath(f, SRC)
        if rel.startswith((".", "scripts", "stats", "template")) or "/tests/" in rel or ".test." in rel:
            continue
        try:
            d = yaml.safe_load(open(f, encoding="utf-8"))
        except Exception:  # noqa: BLE001 - malformed or non-rule yaml
            continue
        if not isinstance(d, dict) or not isinstance(d.get("rules"), list):
            continue
        prefix = ".".join(os.path.dirname(rel).split(os.sep))
        for r in d["rules"]:
            md = r.get("metadata") or {}
            cwe = md.get("cwe") or []
            cwe = [cwe] if isinstance(cwe, str) else cwe
            out.append({"id": f"{prefix}.{r.get('id')}", "langs": r.get("languages") or [], "category": md.get("category", ""),
                        "cwe": [m.group(1) for c in cwe for m in [re.search(r"CWE-(\d+)", str(c))] if m]})
    return out


def main():
    rules, crev = load(), crev_rules()
    xref = {}
    for c in crev:
        for e in c.get("semgrep", []):
            xref.setdefault(e, []).append(c["id"])
    lines = ["# Semgrep registry coverage (checklist: rule ids + metadata, local use under the Semgrep Rules License)", "",
             "Generated by `python tools/gap/semgrep.py`. Covered = crev rule with `semgrep:<id>` xref, or (security rules) same-language CWE family match.", "",
             "| language | rules | security | covered (xref) | covered (cwe) | security coverage |", "|---|---|---|---|---|---|"]
    for lang, cl in LANGS.items():
        rs = [r for r in rules if lang in r["langs"]]
        if not rs:
            continue
        pool = [c for c in crev if c["lang"] in cl]
        cwes = {FAMILY.get(w, w) for c in pool for w in c["cwe"]}
        sec = [r for r in rs if r["category"] == "security"]
        x = [r for r in rs if r["id"] in xref]
        cw = [r for r in sec if r["id"] not in xref and any(FAMILY.get(w, w) in cwes for w in r["cwe"])]
        sc = len([r for r in sec if r["id"] in xref]) + len(cw)
        lines.append(f"| {lang} | {len(rs)} | {len(sec)} | {len(x)} | {len(cw)} | {100 * sc / max(1, len(sec)):.1f}% |")
    open(os.path.join(ROOT, "tools/gap/semgrep-coverage.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
