#!/usr/bin/env python3
"""Snyk Code public rule listings (docs.snyk.io) as a gap checklist.

Only the public per-language tables (rule name, CWE) are read, into tools/gap/cache/snyk-<lang>.md
(gitignored); no content is copied into crev. Coverage = a crev rule of the same language shares
the CWE family, or names the rule in xref (snyk:<Rule Name>).

  python tools/gap/snyk.py fetch && python tools/gap/snyk.py
"""
import os, re, sys, urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sonar import crev_rules, FAMILY  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CACHE = os.path.join(ROOT, "tools/gap/cache")

def ensure_cache_module(cache):
    """Fetched sources include .go files; a nested go.mod keeps them out of `go build ./...`."""
    os.makedirs(cache, exist_ok=True)
    p = os.path.join(cache, "go.mod")
    if not os.path.exists(p):
        with open(p, "w", encoding="utf-8") as f:
            f.write("module crevcache\n")
BASE = "https://docs.snyk.io/scan-with-snyk/snyk-code/snyk-code-security-rules/"
PAGES = {"java": ("java-rules", ["java"]), "javascript-typescript": ("javascript-and-typescript-rules", ["javascript", "typescript"]),
         "python": ("python-rules", ["python"]), "go": ("go-rules", ["go"]), "kotlin": ("kotlin-rules", ["kotlin"]),
         "php": ("php-rules", ["php"])}


def fetch():
    ensure_cache_module(CACHE)
    for lang, (page, _) in PAGES.items():
        req = urllib.request.Request(BASE + page + ".md", headers={"User-Agent": "curl/8 (crev gap checklist)"})
        with urllib.request.urlopen(req, timeout=60) as r:
            open(os.path.join(CACHE, f"snyk-{lang}.md"), "wb").write(r.read())


def rows(lang):
    out = []
    for line in open(os.path.join(CACHE, f"snyk-{lang}.md"), encoding="utf-8"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 2 and re.search(r"CWE-\d+", cells[1]) and cells[0] != "Rule Name":
            out.append((cells[0], re.findall(r"CWE-0*(\d+)", cells[1])))
    return out


def main():
    crev = crev_rules()
    lines = ["# Snyk Code rule coverage (checklist: public docs.snyk.io rule tables, names + CWE only)", "",
             "Generated by `python tools/gap/snyk.py`. Covered = crev rule of the same language with the same CWE family or a `snyk:` xref.", "",
             "| language | Snyk rules | covered | coverage | uncovered CWEs |", "|---|---|---|---|---|"]
    for lang, (_, cl) in PAGES.items():
        if not os.path.exists(os.path.join(CACHE, f"snyk-{lang}.md")):
            continue
        rs = rows(lang)
        pool = [c for c in crev if c["lang"] in cl]
        cwes = {FAMILY.get(w, w) for c in pool for w in c["cwe"]}
        names = {n for c in pool for n in c.get("snyk", [])}
        cov = [r for r in rs if r[0] in names or any(FAMILY.get(w, w) in cwes for w in r[1])]
        miss = sorted({w for r in rs if r not in cov for w in r[1]}, key=int)
        lines.append(f"| {lang} | {len(rs)} | {len(cov)} | {100 * len(cov) / max(1, len(rs)):.1f}% | {', '.join('CWE-' + m for m in miss)} |")
    open(os.path.join(ROOT, "tools/gap/snyk-coverage.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    fetch() if sys.argv[1:] == ["fetch"] else main()
