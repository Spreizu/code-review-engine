"""Pack layout: one directory per pack (language / framework / file type), small files per topic.

    rules/packs/<pack>/<topic>.yaml       hand-edited rules (header says HAND-EDITED)
    rules/packs/<pack>/<topic>.gen.yaml   generated by rulegen.py from specs/*.py (never edit)

route(rule, origin) decides (pack, topic) for a rule; `origin` is the spec module name (generated)
or the legacy pack file stem (one-time migration). Cross-cutting themes (taint, llm, cert, appsec,
supply-chain, cloud, ci, simplification) are not packs: the rule goes to its language/framework
pack, the theme becomes the topic file and a `tags` entry. Rules inside a file are sorted by id
so regenerations give clean diffs.
"""
import os
import re

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PACKS_DIR = os.path.join(ROOT, "rules", "packs")

# legacy cross-cutting origins -> theme (topic + tag)
THEMES = {
    "taint": "taint", "llm": "llm", "cert_java": "cert", "cert-java": "cert", "appsec": "appsec",
    "java-security": "appsec", "python-security": "appsec", "supply_chain": "supply-chain",
    "supply-chain": "supply-chain", "cloud": "cloud", "ci": "ci", "maint": "maintainability",
}
# language -> pack for cross-cutting rules
LANG_PACK = {
    "java": "java", "kotlin": "kotlin", "python": "python", "go": "go", "php": "php",
    "javascript": "javascript", "typescript": "typescript", "tsx": "typescript", "jsx": "javascript",
    "hcl": "terraform", "dockerfile": "docker", "xml": "maven", "html": "html",
}
# origin pack -> pack (the legacy pack name is not a language/framework)
ORIGIN_PACK = {"java-security": "java", "python-security": "python", "vue-vapor": "vue"}

KIND_TOPIC = {
    "security": "security",
    "deprecation": "migration", "removal": "migration", "migration": "migration",
    "modernization": "modernization",
}
# topics larger than this are split by the major version of the pack's version dimension
MAX_TOPIC = 120


def theme_of(origin):
    o = origin.replace("_", "-")
    if o.startswith("simplify-"):
        return "simplification"
    return THEMES.get(origin) or THEMES.get(o)


def _files(rule):
    return " ".join((rule.get("detection") or {}).get("files") or [])


def route(rule, origin):
    """(pack, topic) for a rule coming from spec/legacy pack `origin`."""
    o = origin.replace("_", "-")
    o = re.sub(r"-extended$", "", o)
    theme = theme_of(origin)
    lang = rule.get("language")
    if o == "vue-vapor":
        return "vue", "vapor"
    if theme in ("ci", "supply-chain") or (lang == "yaml" and theme):
        f = _files(rule)
        if ".github/workflows" in f:
            pack = "github-actions"
        elif "gitlab-ci" in f:
            pack = "gitlab-ci"
        elif lang == "json":
            pack = "package-json"
        else:
            pack = LANG_PACK.get(lang, lang)
        topic = theme if theme == "supply-chain" else KIND_TOPIC.get(rule.get("kind"), "quality")
        return pack, topic
    if theme:
        pack = LANG_PACK.get(lang, lang)
        if theme == "cloud":
            return pack, "cloud"
        if theme == "appsec":
            return pack, "security"
        return pack, theme
    if o.startswith("simplify-"):
        return o[len("simplify-"):], "simplification"
    pack = ORIGIN_PACK.get(o, o)
    return pack, KIND_TOPIC.get(rule.get("kind"), "quality")


def add_theme_tag(rule, origin):
    theme = theme_of(origin)
    if theme and theme != "ci":
        tags = list(rule.get("tags") or [])
        if theme not in tags:
            tags.append(theme)
        rule["tags"] = tags
    return rule


_VER = re.compile(r"(\d+)")


def _major(rule, pack):
    """Major version a migration rule targets: the lowest bound of the pack's own dimension."""
    a = rule.get("applies_to") or {}
    rng = a.get(pack) or next((v for v in a.values() if isinstance(v, str) and v != "*"), "")
    m = _VER.search(str(rng))
    return m.group(1) if m else None


def split_large(pack, topic, rules):
    """Split an oversized migration topic into migration-v<major> files; versions with fewer than
    MIN_SPLIT rules (and rules without a version) stay in the plain topic file."""
    if len(rules) <= MAX_TOPIC or topic != "migration":
        return {topic: rules}
    by = {}
    for r in rules:
        by.setdefault(_major(r, pack), []).append(r)
    out = {}
    for mj, rs in by.items():
        key = f"{topic}-v{mj}" if mj and len(rs) >= MIN_SPLIT else topic
        out.setdefault(key, []).extend(rs)
    return out


MIN_SPLIT = 5


HAND_HEADER = ("# HAND-EDITED rule file: pack {pack}, topic {topic}. Edit here directly; keep rules sorted by id.\n"
               "# (Generated rules for this pack live in *.gen.yaml next to this file; never edit those.)\n")
GEN_HEADER = ("# GENERATED by tools/rulegen/rulegen.py from tools/rulegen/specs/ - edit the spec, not this file.\n"
              "# Pack {pack}, topic {topic}. Every source.quote is verified verbatim against source.url by `rulegen.py verify`.\n")


def dump(path, pack, topic, rules, generated, extra_header=""):
    rules = sorted(rules, key=lambda r: r["id"])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write((GEN_HEADER if generated else HAND_HEADER).format(pack=pack, topic=topic))
        if extra_header:
            f.write(extra_header)
        yaml.safe_dump({"pack": pack, "pack_version": "2026.10.0", "rules": rules}, f, sort_keys=False,
                       allow_unicode=True, width=10000)


def pack_files(generated=None):
    """Every pack file; generated=True/False restricts to *.gen.yaml / hand-edited files."""
    out = []
    for d in sorted(os.listdir(PACKS_DIR)):
        p = os.path.join(PACKS_DIR, d)
        if not os.path.isdir(p):
            continue
        for f in sorted(os.listdir(p)):
            if not f.endswith(".yaml"):
                continue
            g = f.endswith(".gen.yaml")
            if generated is None or g == generated:
                out.append(os.path.join(p, f))
    return out
