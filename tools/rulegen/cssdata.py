#!/usr/bin/env python3
"""cssdata: known CSS names for the CSS pack's "unknown property/pseudo/at-rule" checks.

Sources (official W3C data): @webref/css (curated extract of every CSS-defining spec, incl. FXTF,
SVG and pointer events; MIT) and the CSS WG property index (all-properties.en.json). Writes
internal/engine/data/css-known.txt: one "<kind> <name>" per line, kinds property, descriptor,
pseudo-class, pseudo-element, at-rule. Being permissive is deliberate (drafts count as known):
an unknown-name finding must be a typo or an invented name, never a new-but-real feature.

    python3 tools/rulegen/cssdata.py
"""
import io, json, os, tarfile, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "internal", "engine", "data", "css-known.txt")


def get(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def main():
    meta = json.loads(get("https://registry.npmjs.org/@webref/css/latest"))
    tar = tarfile.open(fileobj=io.BytesIO(get(meta["dist"]["tarball"])))
    css = json.load(tar.extractfile("package/css.json"))
    known = set()
    for p in css["properties"]:
        known.add(("property", p["name"]))
    for p in json.loads(get("https://www.w3.org/Style/CSS/all-properties.en.json")):
        if p["property"] != "--*":
            known.add(("property", p["property"]))
    for a in css["atrules"]:
        known.add(("at-rule", a["name"].lstrip("@")))
        for d in a.get("descriptors") or []:
            known.add(("descriptor", d["name"]))
    for s in css["selectors"]:
        n = s["name"]
        if n.startswith("::"):
            known.add(("pseudo-element", n[2:].split("(")[0]))
        elif n.startswith(":"):
            known.add(("pseudo-class", n[1:].split("(")[0]))
    # CSS 2 single-colon pseudo-elements stay valid with one colon
    for n in ("before", "after", "first-line", "first-letter"):
        known.add(("pseudo-class", n))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("# GENERATED by tools/rulegen/cssdata.py from @webref/css %s + w3.org/Style/CSS/all-properties.en.json\n" % meta["version"])
        for k, n in sorted(known):
            f.write(f"{k} {n}\n")
    print(OUT, len(known))


if __name__ == "__main__":
    main()
