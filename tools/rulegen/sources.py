"""Regenerate sources.yaml: keep curated entries (seed list from sources.md), add every URL cited by a rule pack,
and recompute cited_by for all entries.

    /tmp/venv/bin/python tools/rulegen/sources.py   # rewrite sources.yaml + the generated index in sources.md
"""
import glob
import os
import re
import sys
from collections import OrderedDict

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PACK_ECO = {"java": "java", "spring-boot": "spring", "javascript": "javascript", "typescript": "typescript", "vue": "vue", "nuxt": "nuxt"}


def classify(url):
    u = url.lower()
    if any(h in u for h in ("eslint.org/docs", "typescript-eslint.io/rules", "eslint.vuejs.org/rules")):
        return "lint-rule-xref", "md"
    if "release-notes" in u or "changelog" in u or "/releases" in u:
        return "release-notes", "gh-wiki" if "spring-boot/wiki" in u else "html"
    if "migration" in u or "upgrade" in u or "migrat" in u:
        return "migration", "gh-wiki" if "spring-boot/wiki" in u else "html"
    if "openjdk.org/jeps/" in u:
        return "reference", "jep"
    return "reference", "html"


def main():
    path = os.path.join(ROOT, "sources.yaml")
    cur = yaml.safe_load(open(path, encoding="utf-8"))
    entries = OrderedDict((e["url"], e) for e in cur["sources"])
    for e in entries.values():
        e["cited_by"] = []
    for f in sorted(glob.glob(os.path.join(ROOT, "rules/packs/*/*.yaml"))):
        pack = os.path.basename(os.path.dirname(f))
        for r in yaml.safe_load(open(f, encoding="utf-8"))["rules"]:
            url = r["source"]["url"]
            if url not in entries:
                kind, fetch = classify(url)
                entries[url] = {"url": url, "ecosystem": PACK_ECO.get(pack, pack), "kind": kind, "fetch": fetch,
                                "cadence": "weekly", "doc_version": r["source"].get("doc_version", ""), "cited_by": []}
            entries[url]["cited_by"].append(r["id"])
    for e in entries.values():
        e["cited_by"] = sorted(set(e["cited_by"]))
    cur["sources"] = list(entries.values())
    cur["note"] = ("All URLs returned HTTP 200 on the verified date (rule URLs re-fetched and quote-checked by "
                   "tools/rulegen/rulegen.py verify). Curated seed entries come from sources.md; rule citations are added "
                   "by tools/rulegen/sources.py, which also recomputes cited_by.")
    with open(path, "w", encoding="utf-8") as fh:
        yaml.safe_dump(cur, fh, sort_keys=False, allow_unicode=True, width=200)
    by = {}
    for e in entries.values():
        by.setdefault(e["ecosystem"], [0, 0])
        by[e["ecosystem"]][0] += 1
        by[e["ecosystem"]][1] += bool(e["cited_by"])
    print(f"sources={len(entries)}", {k: f"{v[0]} ({v[1]} cited)" for k, v in by.items()})




def write_md():
    """Rewrite the generated citation index at the end of sources.md (between markers)."""
    md_path = os.path.join(ROOT, "sources.md")
    md = open(md_path, encoding="utf-8").read()
    start, end = "<!-- BEGIN GENERATED CITATIONS -->", "<!-- END GENERATED CITATIONS -->"
    if start in md:
        md = md[:md.index(start)].rstrip() + "\n"
    src = yaml.safe_load(open(os.path.join(ROOT, "sources.yaml"), encoding="utf-8"))["sources"]
    out = [start, "", "## 8. Rule citation index (generated by `tools/rulegen/sources.py`)", "",
           "Every URL a rule cites, grouped by ecosystem, with the number of rules citing it. All were fetched (HTTP 200) "
           "and every rule's `source.quote` was found verbatim (whitespace/case-normalised) on the page on 2026-10-09 "
           "by `tools/rulegen/rulegen.py verify`.", ""]
    for eco in ("java", "spring", "javascript", "typescript", "vue", "nuxt"):
        rows = sorted((e for e in src if e["ecosystem"] == eco and e["cited_by"]), key=lambda e: e["url"])
        out += [f"### {eco} ({len(rows)} URLs, {sum(len(e['cited_by']) for e in rows)} rule citations)", "", "| URL | Kind | Rules |", "|---|---|---|"]
        out += [f"| {e['url']} | {e['kind']} | {len(e['cited_by'])} |" for e in rows]
        out.append("")
    out.append(end)
    open(md_path, "w", encoding="utf-8").write(md + "\n" + "\n".join(out) + "\n")


if __name__ == "__main__":
    main()
    write_md()
