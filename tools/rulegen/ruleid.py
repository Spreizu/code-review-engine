#!/usr/bin/env python3
"""Rule id scheme: <PACK>-<CATEGORY>-<NAME>.

PACK is the pack's code (rules/packs/<pack>/), CATEGORY the topic file's code (security.yaml ->
SEC, ...) and NAME the rest of the legacy id once leading pack / theme / language tokens are
dropped (TAINT-JAVA-SQLI in java/taint -> JAVA-TAINT-SQLI). new_id() is idempotent, so ids that
already follow the scheme are unchanged.

`python3 tools/rulegen/ruleid.py plan` writes rules/data/renames.yaml (legacy id -> id) from the
current pack files; `apply` rewrites every tracked text file that mentions a legacy id. The table is
generator input only (keeps generated ids stable); the engine does not accept legacy ids.
"""
import os, re, subprocess, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PACKS = os.path.join(ROOT, "rules", "packs")
PACK_CODE = {
    "android": "ANDROID", "angular": "NG", "composer": "COMPOSER", "css": "CSS", "docker": "DOCKER", "github-actions": "GHA", "gitlab-ci": "GITLAB",
    "go": "GO", "gradle": "GRADLE", "graphql": "GRAPHQL", "html": "HTML", "java": "JAVA", "javascript": "JS", "json": "JSON", "kotlin": "KT",
    "kubernetes": "KUBE", "maven": "MAVEN", "nuxt-ui": "NUXTUI", "nuxt": "NUXT", "package-json": "PKG", "payload": "PAYLOAD",
    "php": "PHP", "protobuf": "PROTO", "python": "PY", "react": "REACT", "spring-boot": "SB", "terraform": "TF", "typescript": "TS",
    "vue": "VUE", "vueuse": "VUEUSE", "yaml": "YAML", "ytt": "YTT",
}
CAT_CODE = {
    "security": "SEC", "taint": "TAINT", "quality": "QUAL", "maintainability": "MAINT", "migration": "MIG", "modernization": "MOD",
    "simplification": "SIMP", "cert": "CERT", "supply-chain": "SUPPLY", "cloud": "CLOUD", "llm": "LLM", "vapor": "VAPOR", "ci": "CI", "accessibility": "A11Y",
}
THEME_TOKENS = {"SIMP", "TAINT", "APPSEC", "CERT", "LLM", "SC", "MAINT", "A11Y"}


def cat_code(topic):
    if re.match(r"^migration-v\d+$", topic):  # split files share the category (stable across splits)
        return "MIG"
    return CAT_CODE.get(topic, re.sub(r"[^A-Z0-9]", "", topic.upper())[:6])


def new_id(old, pack, topic):
    pc, cc = PACK_CODE.get(pack, pack.upper().replace("-", "")), cat_code(topic)
    toks = old.split("-")
    # language tokens only go when they repeat the pack (APPSEC-JS in javascript), never another
    # language's name inside a rule (SC-DOCKER-GO-INSTALL keeps GO)
    strip = {pc, cc} | THEME_TOKENS | ({"JS", "TS"} if pc in ("JS", "TS") else set())
    i = 0
    while i < len(toks) - 1 and toks[i] in strip:
        i += 1
    return f"{pc}-{cc}-{'-'.join(toks[i:])}"


def pack_files():
    for pack in sorted(os.listdir(PACKS)):
        d = os.path.join(PACKS, pack)
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            if f.endswith(".yaml"):
                yield pack, re.sub(r"(\.gen)?\.yaml$", "", f), os.path.join(d, f)


def plan():
    old = {}
    for pack, topic, f in pack_files():
        for r in (yaml.safe_load(open(f, encoding="utf-8")) or {}).get("rules") or []:
            old[r["id"]] = (pack, topic)
    used, out = set(old), {}
    for oid in sorted(old):
        pack, topic = old[oid]
        nid = new_id(oid, pack, topic)
        if nid == oid:
            continue
        if nid in used:  # keep one more legacy token to stay unique
            pc, cc = nid.split("-")[0], nid.split("-")[1]
            nid = f"{pc}-{cc}-{oid}"
            if nid in used:
                raise SystemExit(f"cannot rename {oid}: {nid} taken")
        used.discard(oid)
        used.add(nid)
        out[oid] = nid
    return out


def load():
    p = os.path.join(ROOT, "tools", "rulegen", "renames.yaml")
    if not os.path.exists(p):
        return {}
    return (yaml.safe_load(open(p, encoding="utf-8")) or {}).get("renamed") or {}


def write(m):
    p = os.path.join(ROOT, "tools", "rulegen", "renames.yaml")
    with open(p, "w", encoding="utf-8") as fh:
        fh.write("# GENERATED by tools/rulegen/ruleid.py: legacy rule id -> <PACK>-<CATEGORY>-<NAME> id.\n"
                 "# Generator input only (stable ids); crev itself accepts current ids only.\n")
        yaml.safe_dump({"renamed": dict(sorted(m.items()))}, fh, sort_keys=False, width=200)


# specs emit legacy ids (rulegen renames on output), so they keep referring to them
SKIP = ("tools/corpus/cache/", "tools/corpus/results/", "tools/rulegen/renames.yaml", "tools/rulegen/specs/")


def apply(m):
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    keys = sorted(m, key=len, reverse=True)
    rx = re.compile(r"(?<![A-Za-z0-9_-])(" + "|".join(map(re.escape, keys)) + r")(?![A-Za-z0-9_-])")
    n = 0
    for f in files:
        if f.startswith(SKIP) or not re.search(r"\.(ya?ml|go|py|md|json|txt|ts|js|vue|html)$", f):
            continue
        p = os.path.join(ROOT, f)
        try:
            s = open(p, encoding="utf-8").read()
        except (UnicodeDecodeError, FileNotFoundError):
            continue
        t = rx.sub(lambda mm: m[mm.group(1)], s)
        if t != s:
            open(p, "w", encoding="utf-8").write(t)
            n += 1
    print("rewrote", n, "files")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "plan"
    if cmd == "plan":
        m = load()
        m.update(plan())
        write(m)
        print(len(m), "renames")
    elif cmd == "apply":
        apply(load())
