package main

// autofix: lint auto-fix commit differential. Commits whose message is a linter autofix
// (eslint --fix, ruff --fix, gofmt, prettier, lint:fix, ...) are mined from corpus clone history
// and/or GitHub commit search. Files the commit modified are fetched at the parent and at the fix
// and scanned with crev. A finding that disappears is a labelled true positive; one that appears
// only after the fix counts against the rule.
//
//	go run ./tools/corpus autofix -label after -crev BIN
//
// API responses and file bodies are cached under tools/corpus/cache/autofix (gitignored).

import (
	"encoding/json"
	"flag"
	"fmt"
	"net/url"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

var autofixMsg = regexp.MustCompile(`(?i)(\blint[- ]fix\b|\bautofix\b|\bauto-fix\b|eslint --fix|oxlint --fix|yarn lint:fix|npm run lint:fix|pnpm (run )?lint:fix|ruff (check )?--fix|\bruff format\b|\bgofmt\b|\bgoimports\b|golangci-lint[^\n]{0,40}--fix|php-cs-fixer|\bprettier --write\b|\bspotlessApply\b|\bapply.*lint.*fix\b)`)

type autofixCommit struct {
	Repo    string `json:"repo"` // GitHub owner/name
	SHA     string `json:"sha"`
	Message string `json:"message"`
	Source  string `json:"source"` // git | github
}

func githubName(raw string) string {
	u := strings.TrimSuffix(strings.TrimSuffix(raw, ".git"), "/")
	if i := strings.Index(u, "github.com/"); i >= 0 {
		return strings.Trim(u[i+len("github.com/"):], "/")
	}
	return ""
}

func autofix(args []string) {
	fs := flag.NewFlagSet("autofix", flag.ExitOnError)
	bin := fs.String("crev", "", "crev binary")
	label := fs.String("label", "after", "results label")
	only := fs.String("repos", "", "comma-separated corpus repo names")
	deepen := fs.Int("deepen", 0, "git fetch --deepen on each clone (slow on blobless cache; default 0 = GitHub API only)")
	maxPer := fs.Int("max-per-repo", 12, "max autofix commits to scan per repo")
	fs.Parse(args)
	if *bin == "" {
		die(fmt.Errorf("-crev is required"))
	}
	stats := map[string]*FixStat{}
	used, skipped := 0, 0
	var report strings.Builder
	for _, r := range selected(load(), *only, "oss") {
		gh := githubCanonical(githubName(r.URL))
		var commits []autofixCommit
		if *deepen > 0 {
			commits = append(commits, gitAutofixCommits(r, *deepen, *maxPer)...)
		}
		if len(commits) < *maxPer && gh != "" {
			for _, c := range githubAutofixCommits(gh, *maxPer-len(commits)) {
				dup := false
				for _, have := range commits {
					if have.SHA == c.SHA {
						dup = true
						break
					}
				}
				if !dup {
					commits = append(commits, c)
				}
			}
		}
		if len(commits) > *maxPer {
			commits = commits[:*maxPer]
		}
		fmt.Printf("%-22s %d autofix commits\n", r.Name, len(commits))
		for _, c := range commits {
			if gh == "" {
				skipped++
				continue
			}
			c.Repo = gh
			n, gone, came := scanAutofix(*bin, gh, c, stats)
			if n == 0 {
				skipped++
				continue
			}
			used++
			fmt.Fprintf(&report, "| %s@%s | %d | %s | %s |\n", gh, c.SHA[:min(10, len(c.SHA))], n, strings.Join(gone, " "), strings.Join(came, " "))
		}
	}
	out := filepath.Join(dir, "results", *label)
	die(os.MkdirAll(out, 0o755))
	j, _ := json.MarshalIndent(stats, "", " ")
	die(os.WriteFile(filepath.Join(out, "autofix.json"), j, 0o644))
	md := fmt.Sprintf("# Lint autofix-commit differential\n\nGenerated by `go run ./tools/corpus autofix -label %s`: %d commits scanned (%d skipped). A rule *fixed* a finding when it fired on the parent and not on the autofix; *introduced* when it fires only on the fixed file.\n\n| commit | files | rules the fix removed | rules that fire only after |\n|---|---|---|---|\n%s", *label, used, skipped, report.String())
	ids := make([]string, 0, len(stats))
	for id := range stats {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	md += "\n## Per rule\n\n| rule | fixed | introduced |\n|---|---|---|\n"
	for _, id := range ids {
		md += fmt.Sprintf("| %s | %d | %d |\n", id, stats[id].Fixed, stats[id].Introduced)
	}
	die(os.WriteFile(filepath.Join(out, "autofix.md"), []byte(md), 0o644))
	fmt.Printf("autofix: %d commits, %d skipped, %d rules with evidence -> %s\n", used, skipped, len(stats), out)
}

func gitAutofixCommits(r Repo, deepen, maxN int) []autofixCommit {
	d := cacheDir(r)
	if _, err := os.Stat(filepath.Join(d, ".git")); err != nil {
		return nil
	}
	if deepen > 0 {
		_ = exec.Command("git", "-C", d, "fetch", "-q", "--filter=blob:none", "--deepen", fmt.Sprint(deepen), "origin").Run()
	}
	out, err := exec.Command("git", "-C", d, "log", "--format=%H\t%s", "-i",
		"--grep=lint", "--grep=eslint", "--grep=ruff", "--grep=gofmt", "--grep=prettier",
		"--grep=autofix", "--grep=auto-fix", "--grep=oxlint", "-n", "80").Output()
	if err != nil {
		return nil
	}
	var list []autofixCommit
	for _, line := range strings.Split(string(out), "\n") {
		sha, msg, ok := strings.Cut(strings.TrimSpace(line), "\t")
		if !ok || !autofixMsg.MatchString(msg) {
			continue
		}
		list = append(list, autofixCommit{Repo: githubName(r.URL), SHA: sha, Message: msg, Source: "git"})
		if len(list) >= maxN {
			break
		}
	}
	return list
}

func githubCanonical(repo string) string {
	if repo == "" {
		return ""
	}
	b, err := ghGet("https://api.github.com/repos/"+repo, filepath.Join(dir, "cache", "autofix", strings.ReplaceAll(repo, "/", "_")+".repo.json"))
	if err != nil {
		return repo
	}
	var meta struct {
		FullName string `json:"full_name"`
	}
	if json.Unmarshal(b, &meta) != nil || meta.FullName == "" {
		return repo
	}
	return meta.FullName
}

func githubAutofixCommits(repo string, maxN int) []autofixCommit {
	if maxN <= 0 {
		return nil
	}
	list := githubSearchAutofix(repo, maxN)
	if len(list) >= maxN {
		return list
	}
	for _, c := range githubListAutofix(repo, maxN-len(list)) {
		dup := false
		for _, have := range list {
			if have.SHA == c.SHA {
				dup = true
				break
			}
		}
		if !dup {
			list = append(list, c)
		}
	}
	return list
}

func githubSearchAutofix(repo string, maxN int) []autofixCommit {
	q := url.QueryEscape("repo:" + repo + " lint fix")
	cache := filepath.Join(dir, "cache", "autofix", strings.ReplaceAll(repo, "/", "_")+".search.json")
	b, err := ghGet("https://api.github.com/search/commits?per_page=30&q="+q, cache)
	if err != nil {
		return nil
	}
	var resp struct {
		Items []struct {
			SHA    string `json:"sha"`
			Commit struct {
				Message string `json:"message"`
			} `json:"commit"`
		} `json:"items"`
	}
	if json.Unmarshal(b, &resp) != nil {
		return nil
	}
	var list []autofixCommit
	for _, it := range resp.Items {
		if c, ok := asAutofixCommit(repo, it.SHA, it.Commit.Message, "github"); ok {
			list = append(list, c)
			if len(list) >= maxN {
				break
			}
		}
	}
	return list
}

func githubListAutofix(repo string, maxN int) []autofixCommit {
	var list []autofixCommit
	for page := 1; page <= 3 && len(list) < maxN; page++ {
		b, err := ghGet(
			fmt.Sprintf("https://api.github.com/repos/%s/commits?per_page=100&page=%d", repo, page),
			filepath.Join(dir, "cache", "autofix", strings.ReplaceAll(repo, "/", "_")+fmt.Sprintf(".commits.%d.json", page)),
		)
		if err != nil {
			break
		}
		var items []struct {
			SHA    string `json:"sha"`
			Commit struct {
				Message string `json:"message"`
			} `json:"commit"`
		}
		if json.Unmarshal(b, &items) != nil {
			break
		}
		for _, it := range items {
			if c, ok := asAutofixCommit(repo, it.SHA, it.Commit.Message, "github-list"); ok {
				list = append(list, c)
				if len(list) >= maxN {
					return list
				}
			}
		}
	}
	return list
}

func asAutofixCommit(repo, sha, message, src string) (autofixCommit, bool) {
	msg := strings.Split(message, "\n")[0]
	if autofixMsg.MatchString(message) || autofixMsg.MatchString(msg) {
		return autofixCommit{Repo: repo, SHA: sha, Message: msg, Source: src}, true
	}
	low := strings.ToLower(msg)
	if strings.Contains(low, "lint") && strings.Contains(low, "fix") {
		return autofixCommit{Repo: repo, SHA: sha, Message: msg, Source: src}, true
	}
	return autofixCommit{}, false
}

func scanAutofix(bin, repo string, c autofixCommit, stats map[string]*FixStat) (int, []string, []string) {
	cdir := filepath.Join(dir, "cache", "autofix", c.SHA)
	meta, err := ghGet("https://api.github.com/repos/"+repo+"/commits/"+c.SHA, filepath.Join(cdir, "commit.json"))
	if err != nil {
		return 0, nil, nil
	}
	var cm struct {
		Parents []struct{ SHA string } `json:"parents"`
		Files   []struct {
			Filename, Status string
		} `json:"files"`
	}
	if json.Unmarshal(meta, &cm) != nil || len(cm.Parents) != 1 {
		return 0, nil, nil
	}
	parent := cm.Parents[0].SHA
	tmp, err := os.MkdirTemp("", "crev-autofix-")
	if err != nil {
		return 0, nil, nil
	}
	defer os.RemoveAll(tmp)
	n := 0
	for _, f := range cm.Files {
		ext := strings.ToLower(filepath.Ext(f.Filename))
		if f.Status != "modified" || !fixExt[ext] || n >= 15 || strings.Contains(f.Filename, "..") {
			continue
		}
		ok := true
		for side, ref := range map[string]string{"before": parent, "after": c.SHA} {
			body, err := ghGet("https://raw.githubusercontent.com/"+repo+"/"+ref+"/"+f.Filename, filepath.Join(cdir, side, f.Filename))
			if err != nil {
				ok = false
				break
			}
			p := filepath.Join(tmp, side, f.Filename)
			_ = os.MkdirAll(filepath.Dir(p), 0o755)
			_ = os.WriteFile(p, body, 0o644)
		}
		if ok {
			n++
		}
	}
	if n == 0 {
		return 0, nil, nil
	}
	before, after := scanDir(bin, filepath.Join(tmp, "before")), scanDir(bin, filepath.Join(tmp, "after"))
	keys := map[string]bool{}
	for k := range before {
		keys[k] = true
	}
	for k := range after {
		keys[k] = true
	}
	var gone, came []string
	for k := range keys {
		rule := strings.SplitN(k, "\x00", 2)[0]
		d := before[k] - after[k]
		if d == 0 {
			continue
		}
		s := stats[rule]
		if s == nil {
			s = &FixStat{}
			stats[rule] = s
		}
		ref := repo + "@" + c.SHA[:min(10, len(c.SHA))]
		if d > 0 {
			s.Fixed += d
			gone = append(gone, rule)
		} else {
			s.Introduced -= d
			came = append(came, rule)
		}
		if !slices.Contains(s.Commits, ref) {
			s.Commits = append(s.Commits, ref)
		}
	}
	slices.Sort(gone)
	slices.Sort(came)
	return n, slices.Compact(gone), slices.Compact(came)
}
