package main

// suppressions: mine inline linter disable comments in pinned corpus clones and treat a crev hit
// at a matching location as a labelled true positive (policy: a suppression marks a real issue
// someone chose to accept; reporting still honours the comment).
//
//	go run ./tools/corpus suppressions -label after
//
// Needs tools/corpus/cache clones (`fetch`) and results/<label>/*.json (`run`). Writes
// results/<label>/suppressions.json and suppressions.md. tools/trust compute adds the TPs.

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/elmo/code-review-engine/internal/engine"
	"github.com/elmo/code-review-engine/internal/projcfg"
	"github.com/elmo/code-review-engine/internal/rules"
)

type supSpot struct {
	Repo string `json:"repo"`
	Path string `json:"path"`
	Line int    `json:"line"`
	Tool string `json:"tool"`
	ID   string `json:"id"`
	Text string `json:"text,omitempty"`
}

type supRule struct {
	TP    int       `json:"tp"`
	Spots []supSpot `json:"spots,omitempty"`
}

type supReport struct {
	Rules      map[string]*supRule `json:"rules"`
	Unmatched  []supSpot           `json:"unmatched,omitempty"`
	Files      int                 `json:"files"`
	Comments   int                 `json:"comments"`
	Repos      int                 `json:"repos"`
	UnmatchedN int                 `json:"unmatched_n,omitempty"`
}

func loadRuleEq() (map[string]*rules.Rule, map[string][]string) {
	rs, err := rules.LoadFiles("rules/packs/*/*.yaml")
	die(err)
	die(rules.ApplyBaseData(rs, os.DirFS("rules")))
	byID := map[string]*rules.Rule{}
	byEq := map[string][]string{}
	for _, r := range rs {
		byID[r.ID] = r
		for _, e := range r.Equivalents {
			byEq[e] = append(byEq[e], r.ID)
		}
	}
	return byID, byEq
}

func suppressions(args []string) {
	fs := flag.NewFlagSet("suppressions", flag.ExitOnError)
	label := fs.String("label", "after", "results label (reads results/<label>/*.json, writes suppressions.json)")
	only := fs.String("repos", "", "comma-separated repo names (default all oss+bench in cache)")
	fs.Parse(args)
	byID, byEq := loadRuleEq()
	hits := map[string][]Hit{} // repo -> hits
	for _, rr := range maybeResults(*label) {
		hits[rr.Repo] = rr.Hits
	}
	out := &supReport{Rules: map[string]*supRule{}}
	seen := map[string]bool{}
	for _, r := range selected(load(), *only, "") {
		if r.Kind == "fixtures" {
			continue
		}
		root := cacheDir(r)
		if _, err := os.Stat(root); err != nil {
			continue
		}
		out.Repos++
		byPath := map[string][]Hit{}
		for _, h := range hits[r.Name] {
			byPath[filepath.ToSlash(h.Path)] = append(byPath[filepath.ToSlash(h.Path)], h)
		}
		walkSource(root, func(rel string, src []byte) {
			out.Files++
			fi := projcfg.ParseInline(rel, src)
			all := fi.All()
			if len(all) == 0 && len(byPath[rel]) == 0 {
				return
			}
			for _, s := range all {
				if s.Crev {
					continue
				}
				out.Comments++
			}
			for _, h := range byPath[rel] {
				rule := byID[h.Rule]
				if rule == nil {
					continue
				}
				sb := fi.Match(rel, h.Rule, rule.Equivalents, h.Line, h.Line)
				if sb == nil || sb.Kind != "inline" {
					continue
				}
				k := h.Rule + "|" + r.Name + "|" + rel + "|" + fmt.Sprint(h.Line)
				if seen[k] {
					continue
				}
				seen[k] = true
				st := out.Rules[h.Rule]
				if st == nil {
					st = &supRule{}
					out.Rules[h.Rule] = st
				}
				st.TP++
				st.Spots = append(st.Spots, supSpot{Repo: r.Name, Path: rel, Line: h.Line, Tool: sb.Tool, ID: sb.ID, Text: sb.Source})
			}
			for _, s := range all {
				if s.Crev || len(s.IDs) == 0 {
					continue
				}
				ids := rulesForInline(s, byEq)
				if len(ids) == 0 {
					continue
				}
				hit := false
				for _, id := range ids {
					if st := out.Rules[id]; st != nil {
						for _, sp := range st.Spots {
							if sp.Repo == r.Name && sp.Path == rel && sp.Line >= s.From && sp.Line <= s.To {
								hit = true
								break
							}
						}
					}
				}
				if !hit {
					out.UnmatchedN++
					if len(out.Unmatched) < 200 {
						out.Unmatched = append(out.Unmatched, supSpot{Repo: r.Name, Path: rel, Line: s.Line, Tool: first(s.Tools), ID: s.IDs[0], Text: s.Text})
					}
				}
			}
		})
		fmt.Printf("%-22s comments mined\n", r.Name)
	}
	dst := filepath.Join(dir, "results", *label)
	die(os.MkdirAll(dst, 0o755))
	j, _ := json.MarshalIndent(out, "", " ")
	die(os.WriteFile(filepath.Join(dst, "suppressions.json"), j, 0o644))
	var md strings.Builder
	fmt.Fprintf(&md, "# Inline linter suppressions\n\nGenerated by `go run ./tools/corpus suppressions -label %s`. A crev hit on a line a matching inline disable covers is a labelled true positive (the suppression marks a real issue). Reporting still honours the comment.\n\n%d repos, %d source files, %d disable comments, %d rules with at least one TP, %d targeted comments with no crev hit (not scored: crev is often a subset).\n\n## Per rule\n\n| rule | TP |\n|---|---|\n",
		*label, out.Repos, out.Files, out.Comments, len(out.Rules), out.UnmatchedN)
	ids := make([]string, 0, len(out.Rules))
	for id := range out.Rules {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		fmt.Fprintf(&md, "| %s | %d |\n", id, out.Rules[id].TP)
	}
	die(os.WriteFile(filepath.Join(dst, "suppressions.md"), []byte(md.String()), 0o644))
	fmt.Printf("suppressions: %d repos, %d TP across %d rules, %d unmatched -> %s\n", out.Repos, sumTP(out.Rules), len(out.Rules), out.UnmatchedN, dst)
}

func sumTP(m map[string]*supRule) int {
	n := 0
	for _, s := range m {
		n += s.TP
	}
	return n
}

func first(s []string) string {
	if len(s) == 0 {
		return ""
	}
	return s[0]
}

func rulesForInline(s projcfg.Inline, byEq map[string][]string) []string {
	seen := map[string]bool{}
	var out []string
	for _, t := range s.Tools {
		for _, id := range s.IDs {
			for _, rid := range byEq[t+":"+id] {
				if !seen[rid] {
					seen[rid] = true
					out = append(out, rid)
				}
			}
		}
	}
	return out
}

func maybeResults(label string) []RepoResult {
	files, _ := filepath.Glob(filepath.Join(dir, "results", label, "*.json"))
	var out []RepoResult
	for _, f := range files {
		base := filepath.Base(f)
		if base == "suppressions.json" || base == "autofix.json" || base == "agree.json" || base == "fixdiff.json" || base == "bench-rules.json" || strings.HasSuffix(base, ".md") {
			continue
		}
		var r RepoResult
		b, err := os.ReadFile(f)
		if err != nil || json.Unmarshal(b, &r) != nil || r.Repo == "" {
			continue
		}
		out = append(out, r)
	}
	return out
}

var srcExt = map[string]bool{
	".js": true, ".mjs": true, ".cjs": true, ".ts": true, ".tsx": true, ".jsx": true, ".vue": true,
	".go": true, ".py": true, ".java": true, ".kt": true, ".kts": true, ".php": true, ".yml": true,
	".yaml": true, ".tf": true, ".css": true, ".scss": true, ".html": true, ".htm": true, ".xml": true,
	".proto": true, ".dockerfile": true, ".gradle": true,
}

func isSourceRel(rel string) bool {
	base := strings.ToLower(filepath.Base(rel))
	if base == "dockerfile" || base == "containerfile" || strings.HasPrefix(base, "dockerfile.") {
		return true
	}
	return srcExt[strings.ToLower(filepath.Ext(rel))]
}

func walkSource(root string, fn func(rel string, src []byte)) {
	filepath.WalkDir(root, func(p string, e os.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if e.IsDir() {
			name := e.Name()
			if slices.Contains(engine.DefaultExcludeDirs, name) {
				return filepath.SkipDir
			}
			return nil
		}
		rel, _ := filepath.Rel(root, p)
		rel = filepath.ToSlash(rel)
		if !isSourceRel(rel) {
			return nil
		}
		info, err := e.Info()
		if err != nil || info.Size() > 512*1024 {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return nil
		}
		fn(rel, b)
		return nil
	})
}
