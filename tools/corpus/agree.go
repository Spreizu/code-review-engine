package main

// agree: run real linters on the same pinned corpus clones as crev and score location agreement.
// A diagnostic both tools emit at the same file/line (mapped through xref tool:id) is a labelled
// true positive. crev-only and linter-only spots are reported but not scored as FP/FN: crev often
// implements a subset of the linter rule.
//
//	go run ./tools/corpus agree -label after
//
// Uses whatever of oxlint, ruff, hadolint, yamllint is on PATH. Missing binaries are skipped.
// Needs tools/corpus/cache clones and results/<label>/*.json.

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"time"
)

type lintDiag struct {
	Tool, ID, Path string
	Line           int
}

type agreeRule struct {
	Both     int       `json:"both"`
	CrevOnly int       `json:"crev_only"`
	LintOnly int       `json:"lint_only"`
	Linters  []string  `json:"linters,omitempty"`
	Spots    []supSpot `json:"spots,omitempty"`
}

type agreeReport struct {
	Rules   map[string]*agreeRule `json:"rules"`
	Skipped []string              `json:"skipped,omitempty"`
	Ran     []string              `json:"ran,omitempty"`
	Repos   int                   `json:"repos"`
	Diags   int                   `json:"linter_diagnostics"`
}

func agree(args []string) {
	fs := flag.NewFlagSet("agree", flag.ExitOnError)
	label := fs.String("label", "after", "results label")
	only := fs.String("repos", "", "comma-separated repo names")
	fs.Parse(args)
	byID, byEq := loadRuleEq()
	eqOf := map[string][]string{}
	for id, r := range byID {
		eqOf[id] = r.Equivalents
	}
	runners, skipped := lintRunners()
	out := &agreeReport{Rules: map[string]*agreeRule{}, Skipped: skipped}
	seenBoth := map[string]bool{}
	for _, r := range selected(load(), *only, "") {
		if r.Kind == "fixtures" {
			continue
		}
		root := cacheDir(r)
		if _, err := os.Stat(root); err != nil {
			continue
		}
		crevHits := []Hit{}
		for _, rr := range maybeResults(*label) {
			if rr.Repo == r.Name {
				crevHits = rr.Hits
				break
			}
		}
		var diags []lintDiag
		for _, run := range runners {
			if !run.covers(r) {
				continue
			}
			ds, skip := run.fn(root)
			if skip != "" {
				continue
			}
			if !slices.Contains(out.Ran, run.name) {
				out.Ran = append(out.Ran, run.name)
			}
			for i := range ds {
				ds[i].Path = relPath(root, ds[i].Path)
			}
			diags = append(diags, ds...)
		}
		if len(diags) == 0 && len(crevHits) == 0 {
			continue
		}
		out.Repos++
		out.Diags += len(diags)
		lintAt := map[string][]lintDiag{}
		for _, d := range diags {
			lintAt[d.Tool+":"+d.ID] = append(lintAt[d.Tool+":"+d.ID], d)
		}
		matchedLint := map[string]bool{} // tool:id|path|line
		for _, h := range crevHits {
			if h.Status != "confirmed" && h.Status != "pending_ai" && h.Status != "suppressed" {
				continue
			}
			eq := eqOf[h.Rule]
			agreed := false
			for _, e := range eq {
				for _, d := range lintAt[e] {
					if pathEq(d.Path, h.Path) && abs(d.Line-h.Line) <= 1 {
						agreed = true
						matchedLint[e+"|"+d.Path+"|"+fmt.Sprint(d.Line)] = true
					}
				}
			}
			if !agreed && !(len(eq) > 0 && hasLintFor(eq, lintAt)) {
				continue
			}
			st := out.Rules[h.Rule]
			if st == nil {
				st = &agreeRule{}
				out.Rules[h.Rule] = st
			}
			if agreed {
				k := h.Rule + "|" + r.Name + "|" + h.Path + "|" + fmt.Sprint(h.Line)
				if !seenBoth[k] {
					seenBoth[k] = true
					st.Both++
					st.Spots = append(st.Spots, supSpot{Repo: r.Name, Path: h.Path, Line: h.Line})
				}
				for _, e := range eq {
					tool, _, _ := strings.Cut(e, ":")
					if tool != "" && !slices.Contains(st.Linters, tool) {
						st.Linters = append(st.Linters, tool)
					}
				}
			} else {
				st.CrevOnly++
			}
		}
		for e, ds := range lintAt {
			for _, d := range ds {
				if matchedLint[e+"|"+d.Path+"|"+fmt.Sprint(d.Line)] {
					continue
				}
				for _, rid := range byEq[e] {
					st := out.Rules[rid]
					if st == nil {
						st = &agreeRule{}
						out.Rules[rid] = st
					}
					st.LintOnly++
				}
			}
		}
		fmt.Printf("%-22s %d linter diags\n", r.Name, len(diags))
	}
	dst := filepath.Join(dir, "results", *label)
	die(os.MkdirAll(dst, 0o755))
	j, _ := json.MarshalIndent(out, "", " ")
	die(os.WriteFile(filepath.Join(dst, "agree.json"), j, 0o644))
	var md strings.Builder
	fmt.Fprintf(&md, "# Linter agreement\n\nGenerated by `go run ./tools/corpus agree -label %s`. Ran %s on %d repos (%d diagnostics). Both = crev and the mapped linter fire within one line; those count as labelled true positives. crev-only / linter-only are not scored as FP/FN.\n\nSkipped: %s\n\n| rule | both | crev only | linter only | linters |\n|---|---|---|---|---|\n",
		*label, strings.Join(out.Ran, ", "), out.Repos, out.Diags, strings.Join(out.Skipped, "; "))
	ids := make([]string, 0, len(out.Rules))
	for id := range out.Rules {
		ids = append(ids, id)
	}
	slices.Sort(ids)
	for _, id := range ids {
		s := out.Rules[id]
		if s.Both == 0 && s.CrevOnly == 0 && s.LintOnly == 0 {
			continue
		}
		fmt.Fprintf(&md, "| %s | %d | %d | %d | %s |\n", id, s.Both, s.CrevOnly, s.LintOnly, strings.Join(s.Linters, ", "))
	}
	die(os.WriteFile(filepath.Join(dst, "agree.md"), []byte(md.String()), 0o644))
	n := 0
	for _, s := range out.Rules {
		n += s.Both
	}
	fmt.Printf("agree: %d repos, %d both-fire TPs across %d rules -> %s\n", out.Repos, n, len(out.Rules), dst)
}

func hasLintFor(eq []string, lintAt map[string][]lintDiag) bool {
	for _, e := range eq {
		if len(lintAt[e]) > 0 {
			return true
		}
	}
	return false
}

func pathEq(a, b string) bool {
	return filepath.ToSlash(a) == filepath.ToSlash(b)
}

func relPath(root, p string) string {
	if p == "" {
		return p
	}
	absRoot, err := filepath.Abs(root)
	if err != nil {
		absRoot = root
	}
	absP := p
	if filepath.IsAbs(p) {
		absP = p
	} else if a, err := filepath.Abs(filepath.Join(root, p)); err == nil {
		absP = a
	} else if a, err := filepath.Abs(p); err == nil {
		absP = a
	}
	if rel, err := filepath.Rel(absRoot, absP); err == nil && rel != "." && !strings.HasPrefix(rel, "..") {
		return filepath.ToSlash(rel)
	}
	if strings.HasPrefix(filepath.ToSlash(absP), filepath.ToSlash(absRoot)+"/") {
		return strings.TrimPrefix(filepath.ToSlash(absP), filepath.ToSlash(absRoot)+"/")
	}
	return filepath.ToSlash(strings.TrimPrefix(p, "./"))
}

func abs(n int) int {
	if n < 0 {
		return -n
	}
	return n
}

type lintRunner struct {
	name   string
	covers func(Repo) bool
	fn     func(root string) ([]lintDiag, string)
}

func langCover(langs ...string) func(Repo) bool {
	want := map[string]bool{}
	for _, l := range langs {
		want[l] = true
	}
	return func(r Repo) bool {
		for _, c := range r.Covers {
			if want[c] {
				return true
			}
		}
		return false
	}
}

func lintRunners() ([]lintRunner, []string) {
	var out []lintRunner
	var skipped []string
	if p, err := exec.LookPath("oxlint"); err == nil {
		out = append(out, lintRunner{"oxlint", langCover("javascript", "typescript", "vue", "react"), func(root string) ([]lintDiag, string) {
			return runJSONLinter(root, p, []string{".", "--format", "json"}, parseOxlint)
		}})
	} else {
		skipped = append(skipped, "oxlint not on PATH")
	}
	if p, err := exec.LookPath("ruff"); err == nil {
		out = append(out, lintRunner{"ruff", langCover("python"), func(root string) ([]lintDiag, string) {
			return runJSONLinter(root, p, []string{"check", "--output-format", "json", "."}, parseRuff)
		}})
	} else {
		skipped = append(skipped, "ruff not on PATH")
	}
	if p, err := exec.LookPath("hadolint"); err == nil {
		out = append(out, lintRunner{"hadolint", langCover("docker"), func(root string) ([]lintDiag, string) {
			return runHadolint(root, p)
		}})
	} else {
		skipped = append(skipped, "hadolint not on PATH")
	}
	if p, err := exec.LookPath("yamllint"); err == nil {
		out = append(out, lintRunner{"yamllint", langCover("yaml"), func(root string) ([]lintDiag, string) {
			return runYamllint(root, p)
		}})
	} else {
		skipped = append(skipped, "yamllint not on PATH")
	}
	return out, skipped
}

func runJSONLinter(root, bin string, args []string, parse func([]byte) []lintDiag) ([]lintDiag, string) {
	cmd := exec.Command(bin, args...)
	cmd.Dir = root
	done := make(chan struct{})
	go func() {
		select {
		case <-done:
		case <-time.After(90 * time.Second):
			_ = cmd.Process.Kill()
		}
	}()
	b, _ := cmd.Output()
	close(done)
	return parse(b), ""
}

func parseOxlint(b []byte) []lintDiag {
	var wrap struct {
		Diagnostics []struct {
			Filename string `json:"filename"`
			RuleID   string `json:"ruleId"`
			Code     string `json:"code"`
			Rule     string `json:"rule"`
			Label    string `json:"label"`
			Start    struct {
				Line int `json:"line"`
			} `json:"start"`
			Labels []struct {
				Line int `json:"line"`
			} `json:"labels"`
		} `json:"diagnostics"`
	}
	if json.Unmarshal(b, &wrap) == nil && len(wrap.Diagnostics) > 0 {
		var out []lintDiag
		for _, d := range wrap.Diagnostics {
			id := firstNonEmpty(d.RuleID, d.Rule, d.Code, d.Label)
			line := d.Start.Line
			if line == 0 && len(d.Labels) > 0 {
				line = d.Labels[0].Line
			}
			tool, rid := oxlintXref(id)
			if rid == "" {
				continue
			}
			out = append(out, lintDiag{Tool: tool, ID: rid, Path: d.Filename, Line: line})
		}
		return out
	}
	var arr []map[string]any
	if json.Unmarshal(b, &arr) != nil {
		return nil
	}
	var out []lintDiag
	for _, m := range arr {
		id, _ := m["ruleId"].(string)
		if id == "" {
			id, _ = m["code"].(string)
		}
		if id == "" {
			id, _ = m["rule"].(string)
		}
		fn, _ := m["filename"].(string)
		if fn == "" {
			fn, _ = m["file"].(string)
		}
		line := jsonInt(m["line"])
		if line == 0 {
			if loc, ok := m["location"].(map[string]any); ok {
				line = jsonInt(loc["line"])
			}
		}
		tool, rid := oxlintXref(id)
		if rid == "" {
			continue
		}
		out = append(out, lintDiag{Tool: tool, ID: rid, Path: fn, Line: line})
	}
	return out
}

func oxlintXref(id string) (tool, rule string) {
	id = strings.TrimSpace(id)
	id = strings.TrimSuffix(strings.TrimPrefix(id, "eslint("), ")")
	if id == "" {
		return "", ""
	}
	if strings.Contains(id, "/") {
		return "oxlint", id
	}
	return "eslint", id
}

func parseRuff(b []byte) []lintDiag {
	var arr []struct {
		Code     string `json:"code"`
		Filename string `json:"filename"`
		Location struct {
			Row int `json:"row"`
		} `json:"location"`
	}
	if json.Unmarshal(b, &arr) != nil {
		return nil
	}
	var out []lintDiag
	for _, d := range arr {
		if d.Code == "" {
			continue
		}
		out = append(out, lintDiag{Tool: "ruff", ID: d.Code, Path: d.Filename, Line: d.Location.Row})
	}
	return out
}

func runHadolint(root, bin string) ([]lintDiag, string) {
	var files []string
	filepath.WalkDir(root, func(p string, e os.DirEntry, err error) error {
		if err != nil || e.IsDir() {
			if e != nil && e.IsDir() && slices.Contains([]string{".git", "node_modules", "vendor"}, e.Name()) {
				return filepath.SkipDir
			}
			return nil
		}
		if isDockerfile(p) {
			files = append(files, p)
		}
		return nil
	})
	if len(files) == 0 {
		return nil, ""
	}
	args := append([]string{"-f", "json"}, files...)
	cmd := exec.Command(bin, args...)
	cmd.Dir = root
	b, _ := cmd.Output()
	var arr []struct {
		Code string `json:"code"`
		File string `json:"file"`
		Line int    `json:"line"`
	}
	if json.Unmarshal(b, &arr) != nil {
		return nil, ""
	}
	var out []lintDiag
	for _, d := range arr {
		out = append(out, lintDiag{Tool: "hadolint", ID: d.Code, Path: d.File, Line: d.Line})
	}
	return out, ""
}

func runYamllint(root, bin string) ([]lintDiag, string) {
	cmd := exec.Command(bin, "-f", "parsable", ".")
	cmd.Dir = root
	b, _ := cmd.CombinedOutput()
	var out []lintDiag
	for _, line := range strings.Split(string(b), "\n") {
		if d, ok := yamllintLine(line); ok {
			out = append(out, d)
		}
	}
	return out, ""
}

var yamllintRe = regexp.MustCompile(`^([^:]+):(\d+):\d+:\s+\[[^\]]+\]\s+.*\(([\w-]+)\)\s*$`)

func yamllintLine(line string) (lintDiag, bool) {
	m := yamllintRe.FindStringSubmatch(line)
	if m == nil {
		return lintDiag{}, false
	}
	var ln int
	fmt.Sscanf(m[2], "%d", &ln)
	return lintDiag{Tool: "yamllint", ID: m[3], Path: m[1], Line: ln}, true
}

func isDockerfile(p string) bool {
	b := strings.ToLower(filepath.Base(p))
	return b == "dockerfile" || strings.HasPrefix(b, "dockerfile.") || strings.HasSuffix(b, ".dockerfile")
}

func firstNonEmpty(ss ...string) string {
	for _, s := range ss {
		if s != "" {
			return s
		}
	}
	return ""
}

func jsonInt(v any) int {
	switch n := v.(type) {
	case float64:
		return int(n)
	case int:
		return n
	case json.Number:
		i, _ := n.Int64()
		return int(i)
	}
	return 0
}
